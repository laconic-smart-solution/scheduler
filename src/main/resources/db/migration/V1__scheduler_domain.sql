-- Feature 1: business schema (Oracle). Quartz is not the source of truth.

CREATE TABLE SCHEDULER_ACTION (
    ID              VARCHAR2(36)   NOT NULL,
    ACTION_TYPE     VARCHAR2(32)   NOT NULL,
    PAYLOAD_JSON    CLOB           NOT NULL,
    METADATA_JSON   CLOB,
    CREATED_AT      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    UPDATED_AT      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_SCHEDULER_ACTION PRIMARY KEY (ID)
);

CREATE TABLE SCHEDULER_SCHEDULE (
    ID                  VARCHAR2(36)   NOT NULL,
    ACTION_ID           VARCHAR2(36)   NOT NULL,
    STATUS              VARCHAR2(32)   NOT NULL,
    SCHEDULE_KIND       VARCHAR2(32)   NOT NULL,
    RUN_AT              TIMESTAMP(6) WITH TIME ZONE,
    CRON_EXPRESSION     VARCHAR2(128),
    TIME_ZONE           VARCHAR2(64),
    NEXT_EXECUTION_AT   TIMESTAMP(6) WITH TIME ZONE,
    ATTEMPT_COUNT       NUMBER(10)     DEFAULT 0 NOT NULL,
    MAX_ATTEMPTS        NUMBER(10)     DEFAULT 1 NOT NULL,
    IDEMPOTENCY_KEY     VARCHAR2(128),
    VERSION             NUMBER(19)     DEFAULT 0 NOT NULL,
    CREATED_AT          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    UPDATED_AT          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_SCHEDULER_SCHEDULE PRIMARY KEY (ID),
    CONSTRAINT FK_SCHEDULE_ACTION FOREIGN KEY (ACTION_ID) REFERENCES SCHEDULER_ACTION (ID),
    CONSTRAINT UQ_SCHEDULE_IDEMPOTENCY UNIQUE (IDEMPOTENCY_KEY)
);

CREATE INDEX IX_SCHEDULE_DUE ON SCHEDULER_SCHEDULE (STATUS, NEXT_EXECUTION_AT);

CREATE TABLE SCHEDULER_EXECUTION (
    ID               VARCHAR2(36)   NOT NULL,
    SCHEDULE_ID      VARCHAR2(36)   NOT NULL,
    ACTION_ID        VARCHAR2(36)   NOT NULL,
    ATTEMPT_NO       NUMBER(10)     NOT NULL,
    STATUS           VARCHAR2(32)   NOT NULL,
    SCHEDULED_TIME   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    TRIGGERED_TIME   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    STARTED_AT       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    FINISHED_AT      TIMESTAMP(6) WITH TIME ZONE,
    ERROR_CODE       VARCHAR2(64),
    DETAIL_JSON      CLOB,
    CONSTRAINT PK_SCHEDULER_EXECUTION PRIMARY KEY (ID),
    CONSTRAINT FK_EXECUTION_SCHEDULE FOREIGN KEY (SCHEDULE_ID) REFERENCES SCHEDULER_SCHEDULE (ID),
    CONSTRAINT FK_EXECUTION_ACTION FOREIGN KEY (ACTION_ID) REFERENCES SCHEDULER_ACTION (ID),
    CONSTRAINT UQ_EXECUTION_ATTEMPT UNIQUE (SCHEDULE_ID, ATTEMPT_NO)
);

CREATE INDEX IX_EXECUTION_SCHEDULE ON SCHEDULER_EXECUTION (SCHEDULE_ID);
